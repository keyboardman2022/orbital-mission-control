const {Engine}=require('../server/engine.js');

test('seeded body motion is account scoped, survives restart and ignores satellite mass',t=>{
  const dir=mkdtempSync(join(tmpdir(),'orbital-nbody-world-')),filename=join(dir,'orbital.sqlite');
  let engine=new Engine({filename});
  t.after(()=>{engine.close();rmSync(dir,{recursive:true,force:true});});
  const a=engine.guest().user.id,b=engine.guest().user.id;
  const {worldId}=engine.registerWorld({seed:'body field',options:{layout:'spatial-v7',systems:2,blackHoles:1,stars:4}});
  engine.advanceTo(1000);
  const snapshot=user=>engine.active(user,worldId,3).server.bodyField;
  const start=snapshot(a);
  assert.equal(start.tick,0);
  assert.deepEqual(snapshot(b),start);
  const hole=start.bodies.find(body=>body.kind==='blackHole');
  const input={worldId,referenceBodyId:hole.id,name:'probe',position:{x:2000,y:0,z:0},dimension:3,pitchDeg:0,
    speed:5,directionDeg:90,dynamicsVersion:engine.modelInfo(worldId).model.dynamics.version};
  const small=engine.launch(a,{...input,massKg:1,idempotencyKey:'small-probe'});
  const big=engine.launch(a,{...input,massKg:1e30,idempotencyKey:'large-probe'});
  engine.advanceTo(1720);
  const before=snapshot(a);
  assert.equal(before.tick,720);
  assert.deepEqual(before,snapshot(b));
  assert.notDeepEqual(before.bodies,start.bodies);
  assert.deepEqual(engine.get(a,small.id).state,engine.get(a,big.id).state);
  const track=engine.bodyTrajectory(a,worldId,hole.id).points;
  assert.ok(track.length>=2);
  assert.equal(track[0].tick,0);
  engine.setSpatialPaused(a,worldId,true);
  engine.advanceTo(1960);
  assert.deepEqual(snapshot(a),before);
  assert.equal(snapshot(b).tick,960);
  engine.close();engine=new Engine({filename});
  assert.deepEqual(snapshot(a),before);
  assert.deepEqual(engine.bodyTrajectory(a,worldId,hole.id).points,track);
  engine.switchMap(a,{fromWorldId:worldId,toWorldId:null,switchId:'19c8f104-e40b-4263-8989-d172779627eb'});
  assert.equal(snapshot(a).tick,0);
  assert.equal(snapshot(b).tick,960);
});

test('a collision ends the smaller body’s history and continues the larger body’s track',t=>{
  const engine=new Engine({filename:':memory:'});
  t.after(()=>engine.close());
  const user=engine.guest().user.id,worldId='a'.repeat(64);
  const body=(id,x,vx,massSolar)=>({id,kind:'star',name:id,color:'#abcdef',radius:10,massSolar,orbit:null,
    initial:{x,y:0,z:0,vx,vy:0,vz:0}});
  const world={version:'seeded-systems-v1',seed:'impact',radius:90000,layout:'spatial-v7',motion:'nbody-v1',systems:[
    {id:'s',type:'procedural',x:0,y:0,z:0,extent:150,bodies:[body('a',-100,400,.25),body('b',100,-400,.5)]}
  ]};
  engine.db.prepare('INSERT INTO worlds VALUES (?,?)').run(worldId,JSON.stringify(world));
  engine.active(user,worldId,3);
  engine.advanceTo(300);
  const state=engine.active(user,worldId,3).server.bodyField;
  assert.deepEqual(state.bodies.map(body=>body.id),['merged-1']);
  assert.equal(state.bodies[0].mass,.75);
  assert.equal(state.catalog.find(body=>body.id==='merged-1').continuedFrom,'b');
  const a=engine.bodyTrajectory(user,worldId,'a'),b=engine.bodyTrajectory(user,worldId,'b');
  const merged=engine.bodyTrajectory(user,worldId,'merged-1');
  assert.equal(b.body.endTick,null);
  assert.deepEqual(b.collisions,[a.body.endTick]);
  assert.deepEqual(a.collisions,[a.body.endTick]);
  const {x,y,z}=merged.points[0];
  const wave={origin:{x,y,z},radius:merged.body.radius};
  assert.deepEqual(a.collisionEvents,[{tick:a.body.endTick,otherBodyId:'b',absorbed:true,wave}]);
  assert.deepEqual(b.collisionEvents,[{tick:a.body.endTick,otherBodyId:'a',absorbed:false,wave}]);
  assert.deepEqual(state.catalog.find(body=>body.id==='merged-1').mergeOrigin,wave.origin);
  assert.deepEqual(b.segments.map(body=>body.id),['b','merged-1']);
  assert.deepEqual(b.points.filter(point=>point.tick>a.body.endTick),merged.points.slice(1));
  assert.equal(a.points.at(-1).tick,merged.points[0].tick);
  const contactTick=Math.floor(a.body.endTick);
  const detail=engine.bodyTrajectory(user,worldId,'b',{fromTick:contactTick,toTick:contactTick+1});
  assert.deepEqual(detail.points,b.points.filter(point=>point.tick>=contactTick&&point.tick<=contactTick+1));
  assert.equal(detail.points.length,2);
  assert.throws(()=>engine.bodyTrajectory(user,worldId,'b',{fromTick:0,toTick:1e8}),{status:422});
  assert.equal(merged.body.birthTick,merged.points[0].tick);
  const largeAtContact=b.points.find(point=>point.tick===a.body.endTick);
  assert.ok(Math.abs(a.points.at(-1).x-largeAtContact.x-(-20))<1e-8);
  assert.equal(a.contactFrame.tick,a.body.endTick);
  assert.deepEqual(a.contactFrame.bodies.map(body=>body.id),['a','b']);
  assert.deepEqual(a.contactFrame.bodies.map(body=>body.x),[a.points.at(-1).x,largeAtContact.x]);
  assert.equal(b.contactFrame,undefined);
  assert.equal(merged.contactFrame,undefined);
  assert.deepEqual(engine.bodyFrame(user,worldId,0).bodies.map(body=>body.id),['a','b']);
  assert.deepEqual(engine.bodyFrame(user,worldId,merged.body.birthTick+1).bodies.map(body=>body.id),['merged-1']);

  const legacy=engine.bodyFields.get(user,worldId).serialize();
  legacy.catalog=legacy.catalog.map(({continuedFrom,absorbedFrom,mergeOrigin,...body})=>body);
  engine.bodyFields.forget(user,worldId);
  engine.bodyFields.open(user,worldId,world,legacy);
  const restored=engine.bodyTrajectory(user,worldId,'b');
  assert.deepEqual(restored.points,b.points);
  assert.deepEqual(restored.collisionEvents,b.collisionEvents);
  assert.deepEqual(engine.bodyTrajectory(user,worldId,'a').collisionEvents,a.collisionEvents);
});

test('simulation speed advances bodies and satellites together without changing the path or other accounts',t=>{
  const dir=mkdtempSync(join(tmpdir(),'orbital-nbody-speed-')),filename=join(dir,'orbital.sqlite');
  let engine=new Engine({filename});
  t.after(()=>{engine.close();rmSync(dir,{recursive:true,force:true});});
  const a=engine.guest().user.id,b=engine.guest().user.id;
  const {worldId}=engine.registerWorld({seed:'simulation speed',options:{layout:'spatial-v8',systems:2,stars:6,blackHoles:0}});
  const clock=user=>engine.active(user,worldId,3).server;
  const body=clock(a).bodyField.bodies[0];
  clock(b);
  const input={worldId,referenceBodyId:body.id,name:'probe',position:{x:2400,y:0,z:0},dimension:3,pitchDeg:0,
    speed:5,directionDeg:90,massKg:1000,dynamicsVersion:'seeded-nbody-v1',idempotencyKey:'timed-probe'};
  const fast=engine.launch(a,input),slow=engine.launch(b,input);
  assert.throws(()=>engine.setSpatialRate(a,worldId,3),{status:422});
  assert.equal(engine.setSpatialRate(a,worldId,16).server.tick,0);
  engine.advanceTo(30);
  assert.equal(clock(a).tick,480);
  assert.equal(clock(a).bodyField.tick,480);
  assert.equal(engine.get(a,fast.id).state.fieldTick,480);
  assert.equal(clock(b).tick,30);
  assert.equal(engine.get(b,slow.id).state.fieldTick,30);
  const saved=engine.get(a,fast.id).state;
  engine.setSpatialPaused(a,worldId,true);
  assert.equal(engine.setSpatialRate(a,worldId,4).server.tick,480);
  engine.advanceTo(480);
  assert.deepEqual(engine.get(b,slow.id).state,saved);
  assert.deepEqual(clock(a).bodyField,clock(b).bodyField);
  engine.close();engine=new Engine({filename});
  assert.equal(clock(a).simulationRate,4);
  assert.equal(clock(a).paused,true);
  engine.setSpatialPaused(a,worldId,false);
  engine.advanceTo(540);
  assert.equal(clock(a).tick,720);
  assert.equal(clock(a).bodyField.tick,720);
  assert.equal(engine.get(a,fast.id).state.fieldTick,720);
  assert.equal(clock(b).tick,540);
});

test('high-speed streams provide confirmed intermediate points for both stars and satellites',t=>{
  const dir=mkdtempSync(join(tmpdir(),'orbital-nbody-live-path-'));
  const engine=new Engine({filename:join(dir,'orbital.sqlite')});
  t.after(()=>{engine.close();rmSync(dir,{recursive:true,force:true});});
  const user=engine.guest().user.id;
  const {worldId}=engine.registerWorld({seed:'high speed stream',options:{layout:'spatial-v8',systems:2,stars:6,blackHoles:0}});
  const start=engine.setSpatialRate(user,worldId,32).server.bodyField;
  const body=start.bodies[0];
  const flight=engine.launch(user,{worldId,referenceBodyId:body.id,name:'probe',position:{x:2400,y:0,z:0},
    dimension:3,pitchDeg:0,speed:5,directionDeg:90,massKg:1000,dynamicsVersion:'seeded-nbody-v1',idempotencyKey:'live-probe'});
  engine.advanceTo(15);
  const ordinary=engine.list(user,{worldId,dimension:3});
  const streamed=engine.list(user,{worldId,dimension:3,includeLive:true});
  assert.equal(streamed.server.tick,480);
  assert.equal(ordinary.server.bodyLivePath,undefined);
  assert.equal(ordinary.satellites[0].livePath,undefined);
  assert.deepEqual(streamed.server.bodyLivePath.map(frame=>frame.tick),[120,240,360,480]);
  assert.deepEqual(streamed.satellites[0].livePath.map(point=>point[0]),[120,240,360,480]);
  const current=streamed.satellites[0].state;
  assert.equal(streamed.satellites[0].id,flight.id);
  assert.deepEqual(streamed.satellites[0].livePath.at(-1),[480,current.x,current.y,current.z]);
  engine.setSpatialPaused(user,worldId,true);
  engine.advanceTo(21);
  assert.deepEqual(engine.list(user,{worldId,dimension:3,includeLive:true}).server.bodyLivePath,streamed.server.bodyLivePath);
  assert.equal(engine.setSpatialRate(user,worldId,100).server.simulationRate,100);
  assert.equal(engine.setSpatialPaused(user,worldId,false).server.bodyField.tick,480);
  engine.advanceTo(22);
  const at100=engine.list(user,{worldId,dimension:3,includeLive:true});
  assert.equal(at100.server.bodyField.tick,580);
  assert.equal(at100.satellites[0].state.fieldTick,580);
});
